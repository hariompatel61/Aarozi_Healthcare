# Pre-compute reverse lookup: forbidden word → canonical term
_REVERSE_LOOKUP: dict[str, str] = {}
for _canonical, _synonyms in FORBIDDEN_SYNONYMS.items():
    for _syn in _synonyms:
        _REVERSE_LOOKUP[_syn] = _canonical


def is_canonical(term: str) -> bool:
    """Return True if the term is a canonical entity name."""
    return term in CANONICAL_ENTITIES


def lookup_canonical(word: str) -> str | None:
    """Given a forbidden synonym, return the canonical term it should be replaced with.

    Returns None if the word is not a known forbidden synonym.
    """
    return _REVERSE_LOOKUP.get(word)


def validate_term(word: str) -> tuple[bool, str | None]:
    """Validate whether a word is acceptable in domain context.

    Returns:
        (True, None)            — word is a canonical term, acceptable.
        (False, canonical_term) — word is a forbidden synonym, use canonical_term instead.
        (True, None)            — word is neither canonical nor forbidden, acceptable (not a domain term).
    """
    if word in CANONICAL_ENTITIES:
        return (True, None)
    canonical = _REVERSE_LOOKUP.get(word)
    if canonical is not None:
        return (False, canonical)
    return (True, None)
